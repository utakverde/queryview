-- dbsamelco_salesmain1026, dbsamelco_salesbasey1026, dbsamelco_salescatbalogan1026, dbsamelco_salesvillareal1026.
-- No billing rows are loaded by this script. It creates only missing destination tables.
-- Source Entry remains an ordinary column. Identity is (source_database, source_record_key).
-- BASEY billhistory column `name` is case-only versus `Name`; canonical destination column is `Name`.
-- Union columns absent from any source are nullable. Source DOUBLE(M,D) is widened to DOUBLE to avoid target-scale rounding.
-- Metadata defaults are NULL where nullable; replication must explicitly write all source fields.
-- Existing destination tables are not dropped or altered.

